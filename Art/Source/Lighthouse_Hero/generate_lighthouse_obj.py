def rock_plinth():
    m = Mesh("SM_BB_LH_RockPlinth")
    # Faceted irregular basalt blocks ring the tower foot; all faces are visual-only.
    for i in range(40):
        a = math.tau * i / 40 + RNG.uniform(-0.035, 0.035)
        r = RNG.uniform(420, 715)
        cx, cy = math.cos(a) * r, math.sin(a) * r
        rx, ry, rz = RNG.uniform(68, 150), RNG.uniform(52, 128), RNG.uniform(55, 150)
        cx -= math.cos(a) * 35
        cy -= math.sin(a) * 35
        # Low-poly triangulated rock ellipsoid with deterministic coarse variation.
        rings = []
        steps, sides = 5, 9
        for j in range(steps + 1):
            lat = -math.pi / 2 + math.pi * j / steps
            row = []
            for k in range(sides):
                lon = math.tau * k / sides
                variation = RNG.uniform(0.82, 1.18)
                row.append(m.v((cx + rx * math.cos(lat) * math.cos(lon) * variation,
                                cy + ry * math.cos(lat) * math.sin(lon) * variation,
                                -48 + rz * math.sin(lat) * variation)))
            rings.append(row)
        for j in range(steps):
            for k in range(sides):
                nk = (k + 1) % sides
                m.face("WetRock", rings[j][k], rings[j][nk], rings[j + 1][nk])
                m.face("WetRock", rings[j][k], rings[j + 1][nk], rings[j + 1][k])
    return m


